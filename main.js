  function initCheckoutPage() {
    var main = document.querySelector("[data-checkout-page]");
    if (!main) return;

    var emptyEl = main.querySelector("[data-checkout-empty]");
    var flowEl = main.querySelector("[data-checkout-flow]");
    var cart = readCart();

    if (!cart.length) {
      if (emptyEl) emptyEl.hidden = false;
      if (flowEl) flowEl.hidden = true;
      return;
    }
    if (emptyEl) emptyEl.hidden = true;
    if (flowEl) flowEl.hidden = false;

    main.querySelectorAll("[data-location-fields]").forEach(function (root) {
      if (window.CITTACICO_LOCATIONS) window.CITTACICO_LOCATIONS.bind(root);
    });

    /* The markup carries the no-payment wording, so only the live case
       needs rewriting. Connecting Stripe later touches nothing else. */
    if (paymentsEnabled()) {
      var noteEl = main.querySelector("[data-checkout-payment-note]");
      if (noteEl) {
        noteEl.textContent =
          "Payment is taken by Stripe on a secure page of their own. Card and " +
          "wallet details are entered there and never touch this site.";
      }
      var submitEl = main.querySelector("[data-checkout-submit]");
      if (submitEl) submitEl.textContent = "Continue to secure payment";
      var continueEl = main.querySelector("[data-checkout-continue-label]");
      if (continueEl) continueEl.textContent = "Continue to payment";
    }

    var step = 1;
    var steps = main.querySelectorAll("[data-checkout-step]");
    var indicators = main.querySelectorAll("[data-checkout-indicator]");
    var form = main.querySelector("#checkout-form");
    var checkoutEmail = "";

    function showStep(n) {
      step = n;
      steps.forEach(function (el) {
        var s = parseInt(el.getAttribute("data-checkout-step"), 10);
        var active = s === n;
        el.classList.toggle("is-active", active);
        el.hidden = !active;
      });
      indicators.forEach(function (el) {
        var s = parseInt(el.getAttribute("data-checkout-indicator"), 10);
        el.classList.toggle("is-current", s === n);
        el.classList.toggle("is-done", s < n);
      });
    }

    function validateCurrentStep() {
      var stepEl = main.querySelector('[data-checkout-step="' + step + '"]');
      if (!stepEl) return false;
      var fields = stepEl.querySelectorAll("input, select, textarea");
      for (var i = 0; i < fields.length; i++) {
        if (!fields[i].checkValidity()) {
          fields[i].reportValidity();
          return false;
        }
      }
      return true;
    }

    function renderCheckoutSummary() {
      cart = readCart();
      var itemsRoot = main.querySelector("[data-checkout-line-items]");
      var countEl = main.querySelector("[data-checkout-count]");
      var subEl = main.querySelector("[data-checkout-subtotal]");
      var shipEl = main.querySelector("[data-checkout-shipping]");
      var taxEl = main.querySelector("[data-checkout-tax]");
      var totalEl = main.querySelector("[data-checkout-total]");
      if (!itemsRoot || !countEl || !subEl || !shipEl || !taxEl || !totalEl) return;

      var subtotal = cartSubtotal();
      var shipping = 0;
      var tax = 0;
      var total = subtotal + shipping + tax;

      var count = cart.reduce(function (sum, item) {
        return sum + item.quantity;
      }, 0);
      countEl.textContent = "(" + count + ")";

      if (!cart.length) {
        itemsRoot.innerHTML = "";
        subEl.textContent = formatPriceDetailed(0);
        shipEl.textContent = formatPriceDetailed(0);
        taxEl.textContent = formatPriceDetailed(0);
        totalEl.textContent = formatPriceDetailed(0);
        return;
      }

      itemsRoot.innerHTML = cart
        .map(function (item) {
          var product = getProduct(item.slug) || {};
          var thumb = product.number || "—";
          var line = item.price * item.quantity;
          return (
            '<div class="checkout-line-item">' +
            '<a class="checkout-line-thumb" href="product.html?slug=' +
            item.slug +
            '">' +
            thumb +
            "</a>" +
            '<div class="checkout-line-body">' +
            '<p class="checkout-line-name"><a href="product.html?slug=' +
            item.slug +
            '">' +
            item.name +
            "</a></p>" +
            '<p class="checkout-line-meta">Qty ' +
            item.quantity +
            "</p>" +
            '<p class="checkout-line-price">' +
            formatPriceDetailed(line) +
            "</p>" +
            "</div>" +
            "</div>"
          );
        })
        .join("");

      subEl.textContent = formatPriceDetailed(subtotal);
      shipEl.textContent = formatPriceDetailed(shipping);
      taxEl.textContent = formatPriceDetailed(tax);
      totalEl.textContent = formatPriceDetailed(total);
    }

    main.addEventListener("click", function (e) {
      var nextBtn = e.target.closest("[data-checkout-next]");
      if (nextBtn) {
        e.preventDefault();
        if (!validateCurrentStep()) return;
        if (step === 1) {
          var emailInput = form.querySelector('input[name="email"]');
          checkoutEmail = emailInput ? emailInput.value.trim() : "";
        }
        if (step === 2) renderDeliveryReview();
        if (step < 3) showStep(step + 1);
        return;
      }

      var backBtn = e.target.closest("[data-checkout-back]");
      if (backBtn) {
        e.preventDefault();
        if (step > 1) showStep(step - 1);
      }
    });

    /* Payment details live on Stripe's page, so step three shows the client
       what they are about to confirm rather than asking for a card. */
    function renderDeliveryReview() {
      var target = main.querySelector("[data-checkout-review-address]");
      if (!target || !form) return;
      var fd = new FormData(form);
      target.textContent = ["fullName", "address1", "address2", "city", "region", "postal", "country"]
        .map(function (field) {
          return (fd.get(field) || "").toString().trim();
        })
        .filter(Boolean)
        .join(", ");
    }

    if (form) {
      form.addEventListener("keydown", function (e) {
        if (e.key !== "Enter") return;
        if (step < 3) e.preventDefault();
      });
      var errorEl = null;
      function showCheckoutError(message) {
        if (!errorEl) {
          errorEl = document.createElement("p");
          errorEl.className = "checkout-error";
          errorEl.setAttribute("role", "alert");
          var stepEl = main.querySelector('[data-checkout-step="3"]');
          if (stepEl) stepEl.appendChild(errorEl);
        }
        errorEl.textContent = message;
        errorEl.hidden = false;
      }

      /* The confirmation page reads whole dollars; the server answers in cents. */
      function storeConfirmation(order) {
        var payload = {
          id: order.orderNumber,
          email: order.email,
          createdAt: order.placedAt,
          subtotal: order.subtotalCents / 100,
          shipping: order.shippingCents / 100,
          tax: order.taxCents / 100,
          total: order.totalCents / 100,
          items: order.items.map(function (line) {
            return {
              slug: line.slug,
              name: line.name,
              quantity: line.quantity,
              lineTotal: line.lineTotalCents / 100
            };
          })
        };
        try {
          window.sessionStorage.setItem(ORDER_KEY, JSON.stringify(payload));
        } catch (err) {}
      }

      form.addEventListener("submit", function (e) {
        e.preventDefault();
        if (step !== 3) return;
        if (!validateCurrentStep()) return;
        cart = readCart();
        if (!cart.length) return;

        var fd = new FormData(form);
        var email = checkoutEmail || (fd.get("email") || "").toString().trim();
        var locationRoot = form.querySelector("[data-location-fields]");
        var location = window.CITTACICO_LOCATIONS && locationRoot
          ? window.CITTACICO_LOCATIONS.getValues(locationRoot)
          : {
              country: (fd.get("country") || "").toString(),
              region: (fd.get("region") || "").toString()
            };
        var shipping = {
          fullName: (fd.get("fullName") || "").toString(),
          line1: (fd.get("address1") || "").toString(),
          line2: (fd.get("address2") || "").toString(),
          city: (fd.get("city") || "").toString(),
          region: location.region || "",
          postalCode: (fd.get("postal") || "").toString(),
          country: location.country || ""
        };

        if (!window.CITTACICO || !window.CITTACICO.isOnline()) {
          showCheckoutError("The boutique is offline. Please try again shortly.");
          return;
        }

        var submitButton = form.querySelector('[type="submit"]');
        var submitLabel = submitButton ? submitButton.textContent : "";
        if (submitButton) {
          submitButton.disabled = true;
          submitButton.textContent = "Placing your order…";
        }
        if (errorEl) errorEl.hidden = true;

        window.CITTACICO.placeOrder({
          items: cart.map(function (item) {
            return { slug: item.slug, quantity: item.quantity };
          }),
          email: email,
          shipping: shipping,
          marketingOptIn: (fd.get("marketing") || "").toString() === "yes"
        })
          .then(function (result) {
            storeConfirmation(result.order);
            if (result.checkoutUrl) {
              /* Off to Stripe. The bag is cleared by the webhook once paid. */
              window.location.href = result.checkoutUrl;
              return;
            }
            writeCart([]);
            window.location.href = "payment-success.html";
          })
          .catch(function (error) {
            if (submitButton) {
              submitButton.disabled = false;
              submitButton.textContent = submitLabel;
            }
            showCheckoutError(error.message || "The order could not be completed.");
          });
      });
    }

    showStep(1);
    renderCheckoutSummary();
    refreshCheckoutSummary = renderCheckoutSummary;
  }

  function initOrderConfirmationPage() {
    var main = document.querySelector("[data-order-confirmation]");
    if (!main) return;
    var kind = main.getAttribute("data-order-confirmation");
    if (kind !== "success") return;

    var msgEl = main.querySelector("[data-order-confirmation-msg]");
    var idWrap = main.querySelector(".checkout-result-id");
    var idEl = main.querySelector("[data-order-id-display]");
    var summaryRoot = main.querySelector("[data-order-summary]");
    var linesEl = main.querySelector("[data-order-lines]");
    var subEl = main.querySelector("[data-order-subtotal]");
    var shipEl = main.querySelector("[data-order-shipping]");
    var taxEl = main.querySelector("[data-order-tax]");
    var grandEl = main.querySelector("[data-order-grand]");

    var raw = null;
    try {
      raw = window.sessionStorage.getItem(ORDER_KEY);
    } catch (e) {}
    if (!raw) return;

    var order = null;
    try {
      order = JSON.parse(raw);
    } catch (e) {}
    if (!order || !order.id) return;

    /* Landing here with a recorded order means the purchase went through. */
    writeCart([]);

    if (msgEl) {
      var where = order.email || "your email";
      msgEl.textContent = paymentsEnabled()
        ? "A receipt has been sent to " + where + "."
        : "Your order is recorded. The house will write to " +
          where +
          " to confirm the details and arrange settlement.";
    }
    if (idEl) idEl.textContent = order.id;
    if (idWrap) idWrap.hidden = false;

    if (linesEl && order.items && order.items.length) {
      linesEl.innerHTML = order.items
        .map(function (line) {
          return (
            "<li>" +
            '<span class="checkout-result-line-main">' +
            line.name +
            " × " +
            line.quantity +
            "</span>" +
            '<span class="checkout-result-line-price">' +
            formatPriceDetailed(line.lineTotal) +
            "</span>" +
            "</li>"
          );
        })
        .join("");
    }
    if (subEl) subEl.textContent = formatPriceDetailed(order.subtotal || 0);
    if (shipEl) shipEl.textContent = formatPriceDetailed(order.shipping || 0);
    if (taxEl) taxEl.textContent = formatPriceDetailed(order.tax || 0);
    if (grandEl) grandEl.textContent = formatPriceDetailed(order.total || 0);
    if (summaryRoot) summaryRoot.hidden = false;
  }

  hydrateCollectionCards();
  renderShopPage();
  renderProductPage();
  initCheckoutPage();
  initOrderConfirmationPage();

