  function generateOrderId() {
    var d = new Date();
    var y = d.getFullYear();
    var m = String(d.getMonth() + 1).padStart(2, "0");
    var day = String(d.getDate()).padStart(2, "0");
    var hex = Math.random().toString(16).slice(2, 6).toUpperCase();
    return "CCO-" + y + m + day + "-" + hex;
  }

  function getProduct(slug) {
    return products.find(function (product) {
      return product.slug === slug;
    });
  }

  function readCart() {
    try {
      var raw = window.localStorage.getItem(CART_KEY);
      return raw ? JSON.parse(raw) : [];
    } catch (error) {
      return [];
    }
  }

  function writeCart(cart) {
    window.localStorage.setItem(CART_KEY, JSON.stringify(cart));
    updateBagCount();
    renderCartDrawer();
    /* Signed-in clients keep their bag on the server, so it follows them. */
    if (window.CITTACICO && window.CITTACICO.scheduleCartSave) {
      window.CITTACICO.scheduleCartSave();
    }
  }

  function cartCount() {
    return readCart().reduce(function (sum, item) {
      return sum + item.quantity;
    }, 0);
  }

  function cartSubtotal() {
    return readCart().reduce(function (sum, item) {
      return sum + item.price * item.quantity;
    }, 0);
  }

  function addToCartFromProduct(product, quantity) {
    if (!product) return;
    var cart = readCart();
    var existing = cart.find(function (item) {
      return item.slug === product.slug;
    });
    if (existing) existing.quantity += quantity || 1;
    else {
      cart.push({
        slug: product.slug,
        name: product.name,
        category: product.collection,
        price: product.price,
        quantity: quantity || 1
      });
    }
    writeCart(cart);
    openBagDrawer();
  }

  function updateBagItem(slug, quantity) {
    var cart = readCart()
      .map(function (item) {
        if (item.slug === slug) item.quantity = quantity;
        return item;
      })
      .filter(function (item) {
        return item.quantity > 0;
      });
    writeCart(cart);
  }

  function removeCartItem(slug) {
    writeCart(
      readCart().filter(function (item) {
        return item.slug !== slug;
      })
    );
  }

